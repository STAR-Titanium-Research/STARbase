// Directus hook: d1-access-guard (ADR-0011)
//
// Row-level visibility (ADR-0011) is a set of Directus permission filters on the Lab Member policy.
// Four junction collections are part of those filters, so writing a row in one of them changes who
// can read a record:
//
//   sample_co_owners      a co-owner can read and edit the sample
//   project_investigators an investigator can read everything in the project
//   campaign_samples      a campaign's owner can read every sample in it
//   test_sessions_subject a trigger (migration 139) copies the test's first sample into
//                         test_sessions.sample_id, and the sample's owner and co-owners read and
//                         edit the test through it
//
// Directus does not apply item filters to *create* (and `validation` cannot reach across relations),
// so with the plain permissions any member could add themselves to a sample they cannot edit, to a
// project they do not lead, or add someone else's sample to their own campaign, and so read it. This
// hook closes that. It refuses a create (or an update that repoints a parent key) unless the caller
// may change the parent row: for sample_co_owners the sample's owner, for project_investigators the
// project's PI (the parent's DELETE rule, A1a), for test_sessions_subject the test (update rule) and for
// campaign_samples BOTH the campaign and the sample (update rules).
//
// On update, only a parent key that changes is checked. A junction with several guards
// (campaign_samples) grants through the pair of keys, so when either key changes every guard is
// checked on the merged row ({...currentRow, ...payload}).
//
// The check is the parent's own rule (update, or delete where scripts/access_rules.json says 'rule') shipped as
// rules.json (generated by scripts/gen_access_rules.py; a drift check runs in CI and pre-commit), run
// through ItemsService with the caller's accountability, so nothing here restates the rules by hand.
//
// A second check closes a gap in the owner column. Several records may be updated by more people than
// may delete them (a sample: owner and co-owners update, only the owner deletes). Changing the owner
// column would hand delete to whoever changes it, so an update that changes it is refused unless the
// caller passes the record's DELETE rule, i.e. is its current owner. The owner may hand a record over;
// an editor may not take it. rules.json carries that rule as `ownerGuards`, with the list of fields it
// covers: the owner column and `restricted` (A1a). Only the owner switches a record to or from
// Restricted; a Can edit person may not, even though they may edit every other field.
//
// A third check (A1a, `restrictedKeys`) covers moving a record. Moving a sample, operation, test or
// campaign to another project, campaign or sample changes who can see it, which is managing its access
// by another name. When the record, its current sample, or the old or new project, campaign or sample
// is Restricted, the update must pass the record's DELETE rule (its owner), else 403. The flags are read
// straight from the database in the request's transaction (`restricted` is hidden in Directus and the
// parent may not be readable to the caller).
//
// Two more writes could be used to read what a restriction hides, so they are guarded here (the readers
// tables recompute correctly from them; the question is who may write them):
//   * a campaign_samples row (create or repoint) needs the caller to be a READER of the sample
//     (sample_readers, one lookup) on top of the sample's update rule, and when the sample is
//     Restricted its owner (the sample's delete rule);
//   * a change of campaigns.project_id needs the campaign's delete rule (its owner; a Can edit person is
//     refused) and, when the campaign holds a Restricted sample, a Restricted operation or test with that
//     campaign_id, or a sample of a Restricted project, also each of those records' delete rule. Without
//     the last part a campaign owner could move their campaign into a project they created themselves
//     (they are its PI) and so read every record in it. Otherwise only an admin may make the move.
// A test_sessions_subject row on a Restricted test, or a test whose sample is Restricted, needs the
// test's delete rule (the migration-139 trigger derives test_sessions.sample_id from the subject rows).
//
// sample_co_owners and project_investigators use the parent's DELETE rule (A1a: only the owner adds a
// co-owner, only the PI adds an investigator). The Who-has-access endpoint (d1-record-access) writes the
// access tables with system accountability after its own manage check, so it is not guarded here.
//
// "Involved" in the checks above means HIDDEN, not merely flagged: a record is involved when it is Restricted or when d1_private.hidden_records
// lists it (restricted, or under a restricted project, campaign or sample; kept by the readers triggers of migration 166). The bare flag of a parent
// is not enough: an operation on an unrestricted sample in a restricted project is gated by the project, and moving it away lifts that gate. The two
// reads are united (flag OR hidden_records), so an empty hidden_records after a restore can only make the guard stricter, never looser.
// test_sessions_subject is guarded on create, on repointing `item`/`collection`/`test_sessions_id` and on delete: the migration-139 trigger derives
// test_sessions.sample_id from the rows, so changing or removing one moves the test between sample gates.
//
// Until A1b ships, NO non-admin may change `restricted` on any of the four record types, on update or at create (RESTRICT_ADMIN_ONLY below): the files
// and octrees of a restricted record are not yet protected, so letting owners switch it would promise privacy the system cannot keep. Admins can. The
// owner-only logic underneath stays for A1b.
//
// Admins, and calls with no accountability (flows, scripts, other extensions), are not checked.
// Everyone else is, whatever their policy, because the rules are the Lab Member rules.
//
// Creating a parent and its junction rows in one request (a project with investigators, a sample with
// co-owners, a campaign with samples) is allowed. The parent has just been inserted, in the request's
// transaction, so its update rule may not hold for the creator (they named someone else as owner or
// PI), yet the creator is the one making that record. A parent key therefore also passes when the
// parent row was inserted by the current transaction (Postgres: its xmin is this transaction's id),
// without checking its update rule. Only a row INSERTED here and never updated since can match
// (xmin is this transaction AND the OCC version is still 1), so neither a row that merely exists nor
// a pre-existing row that was updated in this transaction (by this request, an FK action or a
// trigger) qualifies, and this never lets a member attach themselves to a record someone else made. The sample of
// a campaign_samples row is still checked (it is a different row) unless it is new too. A row
// created inside a savepoint carries the sub-transaction id and is not recognised: that fails closed
// (refused); Directus does not use savepoints.
// A payload that nests a brand-new parent (no key) is allowed: the caller is creating that record.

import { readFileSync } from 'node:fs';

const RULES = JSON.parse(readFileSync(new URL('./rules.json', import.meta.url), 'utf8'));
const GUARDS = RULES.guards;
const OWNER_GUARDS = RULES.ownerGuards ?? {};
const RESTRICTED_KEYS = RULES.restrictedKeys ?? {};
const CURRENT_USER = '$CURRENT_USER';
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const HIDDEN_TABLE = 'd1_private.hidden_records';

// A1b TURNS THIS OFF. While true, only an administrator can set or change `restricted` (update, and create with restricted = true) on samples,
// operations, tests and campaigns. A1b (which puts files and octrees behind the same readers) sets D1_A1B_RESTRICT_OPEN=true in the Directus
// environment, or flips the default here, and owners then switch it themselves (the owner-only rule below still applies).
export const RESTRICT_ADMIN_ONLY = true;
const restrictAdminOnly = () => RESTRICT_ADMIN_ONLY && process.env.D1_A1B_RESTRICT_OPEN !== 'true';
// the four record types and projects (a project's PI can restrict it, which hides its whole contents)
const restrictable = (collection) => collection === 'projects' || OWNER_GUARDS[collection] !== undefined;
const RESTRICT_REFUSED = 'Restricting a record is not available yet. Ask an administrator.';

// The shape of a Directus ForbiddenError (status 403, code FORBIDDEN), without importing the package.
// `reason` is shown to the person who made the request, so it is plain words (no table names, ids or
// ADR numbers). Directus's own 403 also carries `extensions.reason` ("You don't have permission to
// perform ... for collection ..."), so the guard marks its errors with `source` and gives the
// details as fields (`kind`, `collection`, `parent`, `id`): a client that wants to word the refusal
// itself keys on those, and one that does not shows `reason`. `kind` is 'junction' (a row that grants
// visibility), 'owner' (the owner column) or 'restricted' (the Restricted switch, or a move that
// changes who sees a Restricted record).
const SOURCE = 'd1-access-guard';

function forbidden(reason, details = {}) {
  const err = new Error(reason);
  err.name = 'DirectusError';
  err.status = 403;
  err.code = 'FORBIDDEN';
  err.extensions = { code: 'FORBIDDEN', reason, source: SOURCE, ...details };
  return err;
}

// What a refused junction row says, by junction and parent column (physical_samples is the parent of
// two junctions, so the text follows the junction, not the parent).
const JUNCTION_MESSAGES = {
  'sample_co_owners.sample_id': "Only the sample's owner can add co-owners.",
  'project_investigators.project_id': "Only the project's principal investigator can add investigators.",
  'campaign_samples.campaign_id': 'You can only add samples to a campaign you own or can edit.',
  'campaign_samples.sample_id': 'You can only add a sample to a campaign if you own, co-own or can edit it.',
  'test_sessions_subject.test_sessions_id':
    'You can only change the samples of a test you own, or of a test on a sample you own or co-own.',
};
const UNREADABLE_SAMPLE = 'You cannot see that sample, so you cannot add it to a campaign.';
const RESTRICTED_SAMPLE = "Only the sample's owner can add a restricted sample to a campaign.";
const RESTRICTED_TEST =
  "Only the test's owner can change the samples of a restricted test or of a test on a restricted sample.";
const SUBJECT_MOVE = "Only the test's owner can change the samples of a test that sits under something restricted.";
const REMOVE_FROM_RESTRICTED_CAMPAIGN = "Only the campaign's owner can remove samples from a restricted campaign.";
const CAMPAIGN_MOVE = "Only the campaign's owner can move it to another project.";
const CAMPAIGN_CONTENT =
  'This campaign holds restricted records you do not own, so only an administrator can move it to another project.';
const OWNER_NOUNS = {
  physical_samples: 'sample',
  manufacturing_operations: 'operation',
  test_sessions: 'test',
  campaigns: 'campaign',
};

const isDenied = (err) => err?.code === 'FORBIDDEN' || err?.status === 403;
const isBlank = (value) => value === undefined || value === null || value === '';
const toBool = (value) => value === true || value === 'true' || value === 1;

// Postgres boolean input, as a payload value can reach a boolean column: t/true/y/yes/on/1 and f/false/n/no/off/0, any case,
// padded or not. null = not recognised (including null and undefined): the caller treats that as a CHANGE so the guard runs;
// it never reads an unknown spelling as "unchanged".
const PG_TRUE = new Set(['t', 'true', 'y', 'yes', 'on', '1']);
const PG_FALSE = new Set(['f', 'false', 'n', 'no', 'off', '0']);
function pgBool(value) {
  if (value === true || value === 1) return true;
  if (value === false || value === 0) return false;
  if (typeof value !== 'string') return null;
  const text = value.trim().toLowerCase();
  if (PG_TRUE.has(text)) return true;
  if (PG_FALSE.has(text)) return false;
  return null;
}

// Replace $CURRENT_USER anywhere in a filter (ItemsService does not, only the REST layer does).
function substitute(node, user) {
  if (node === CURRENT_USER) return user;
  if (Array.isArray(node)) return node.map((item) => substitute(item, user));
  if (node && typeof node === 'object') {
    return Object.fromEntries(Object.entries(node).map(([key, value]) => [key, substitute(value, user)]));
  }
  return node;
}

// The parent key a payload names: a bare key, or the key inside a nested object. null = none given;
// undefined = a nested object with no key (a brand-new parent created in the same request).
function parentKey(value, key) {
  if (isBlank(value)) return null;
  if (typeof value !== 'object') return value;
  return isBlank(value[key]) ? undefined : value[key];
}

// The parent table behind each key that moves a record, and the column that is its primary key.
const MOVE_PARENTS = {
  project_id: ['projects', 'project_id'],
  campaign_id: ['campaigns', 'campaign_id'],
  sample_id: ['physical_samples', 'sample_id'],
};
// Operations and tests also depend on the sample they are on, whatever key is being moved.
const HAS_SAMPLE = new Set(['manufacturing_operations', 'test_sessions']);

export default ({ filter }, { services }) => {
  const { ItemsService } = services;

  // True when the caller passes `check.filter` for the record(s) `ids`, run as the caller through
  // ItemsService (the real rule decides). One id is an equality, several are one `_in` read whose
  // answer must name every id.
  async function canPass(check, ids, context) {
    const user = context.accountability.user;
    const list = [...new Set(ids.map(String))];
    const svc = new ItemsService(check.parent, {
      knex: context.database,
      schema: context.schema,
      accountability: context.accountability,
    });
    try {
      const rows = await svc.readByQuery({
        fields: [check.key],
        filter: {
          _and: [
            { [check.key]: list.length === 1 ? { _eq: list[0] } : { _in: list } },
            substitute(check.filter, user),
          ],
        },
        limit: list.length,
      });
      if (list.length === 1) return rows.length > 0;
      return new Set(rows.map((r) => String(r[check.key]))).size === list.length;
    } catch (err) {
      if (isDenied(err)) return false;
      throw err;
    }
  }
  const canUpdate = (check, id, context) => canPass(check, [id], context);

  // The record's own DELETE rule (the owner, with the gates): the rule of ownerGuards.
  function deleteCheck(collection) {
    const guard = OWNER_GUARDS[collection];
    return { parent: collection, key: guard.key, filter: guard.filter };
  }

  // True when the parent row was INSERTED by the transaction this request runs in and not updated
  // since. xmin is the id of the transaction that last wrote the row (insert or update), and
  // pg_current_xact_id() is ours (cast to the 32-bit xid xmin uses), so xmin alone also matches a
  // pre-existing row merely UPDATED here (by this request, an FK action or a trigger side effect).
  // Every guarded parent (physical_samples, projects, campaigns, test_sessions) carries the OCC
  // `version` column, which starts at 1 and which occ_update_trigger_function() raises on every
  // update, so `version = 1` separates "inserted here, never updated" from "updated here". A parent
  // without that column would make this query fail, which refuses the write (fails closed); the
  // phase1 suite checks that all four have it and its trigger.
  async function createdInThisTransaction(check, id, context) {
    const row = await context
      .database(check.parent)
      .where(check.key, id)
      .whereRaw('xmin = pg_current_xact_id()::xid AND version = 1')
      .first(check.key);
    return row !== undefined && row !== null;
  }

  // The ids (of one table) that are Restricted OR listed in d1_private.hidden_records, as strings. `table` is the collection name, `pk` its key.
  // Ids that are not uuids are skipped for the hidden_records read (the column is a uuid); the flag read still sees them.
  async function hiddenIn(db, table, pk, ids, { flag = true } = {}) {
    const list = [...new Set(ids.filter((id) => !isBlank(id)).map(String))];
    const out = new Set();
    if (!list.length) return out;
    if (flag) for (const r of await db(table).whereIn(pk, list).select(pk, 'restricted')) if (toBool(r.restricted)) out.add(String(r[pk]));
    const uuids = list.filter((id) => UUID.test(id));
    if (uuids.length) {
      for (const r of await db(HIDDEN_TABLE).where('kind', table).whereIn('record_id', uuids).select('record_id')) out.add(String(r.record_id));
    }
    return out;
  }

  // The sample a test_sessions_subject row points at (the M2A `item`), or null when it points at something else or nothing.
  const subjectSample = (row) =>
    isBlank(row?.item) || typeof row.item === 'object' || (!isBlank(row.collection) && row.collection !== 'physical_samples') ? null : String(row.item);

  // A change to the subject rows of tests moves each test between sample gates (the migration-139 trigger derives test_sessions.sample_id from the
  // rows). When any of those tests, the sample a test is on, or a sample being added or removed is hidden, the caller must own the tests (their
  // delete rule). Returns true when the change must be refused.
  async function subjectChangeRefused(testIds, sampleIds, context) {
    const db = context.database;
    const tests = [...new Set(testIds.filter((t) => !isBlank(t)).map(String))];
    if (!tests.length) return false;
    const rows = await db('test_sessions').whereIn('session_id', tests).select('session_id', 'sample_id');
    const samples = [...sampleIds, ...rows.map((r) => r.sample_id)].filter((s) => !isBlank(s));
    const hidden =
      (await hiddenIn(db, 'test_sessions', 'session_id', tests)).size > 0 ||
      (await hiddenIn(db, 'physical_samples', 'sample_id', samples)).size > 0;
    return hidden && !(await canPass(deleteCheck('test_sessions'), tests, context));
  }

  // Is this one record hidden (restricted, or under something restricted)?
  async function isHidden(db, table, pk, id) {
    return isBlank(id) ? false : (await hiddenIn(db, table, pk, [id])).has(String(id));
  }

  // The rules that go beyond "the caller may update the parent", run once the update rule has passed.
  // Returns the message of a refusal, or null.
  async function extraCheck(collection, check, id, item, context) {
    const db = context.database;
    const user = context.accountability.user;
    if (collection === 'campaign_samples' && check.parent === 'physical_samples') {
      // A reader of the sample: a sample the caller cannot see cannot be attached to their campaign (the
      // campaign-owner and campaign-PI paths would make them a reader of it) ...
      const reader = await db('sample_readers').where({ record_id: id, user_id: user }).first('record_id');
      if (!reader) return UNREADABLE_SAMPLE;
      // ... and, when the sample is Restricted, its owner.
      if ((await isHidden(db, 'physical_samples', 'sample_id', id)) && !(await canPass(deleteCheck('physical_samples'), [id], context))) {
        return RESTRICTED_SAMPLE;
      }
    }
    if (collection === 'test_sessions_subject' && check.parent === 'test_sessions') {
      // a hidden test, a test on a hidden sample, or a hidden sample being added needs the test's owner
      const sample = subjectSample(item);
      if (await subjectChangeRefused([id], sample ? [sample] : [], context)) return RESTRICTED_TEST;
    }
    return null;
  }

  // Throws a 403 for the first parent the caller may not update. `fields` limits which of the
  // junction's parent keys are checked (the ones an update touches); null checks them all.
  async function enforce(collection, item, fields, context) {
    const checks = (GUARDS[collection] ?? []).filter((c) => !fields || fields.has(c.field));
    for (const check of checks) {
      const id = parentKey(item[check.field], check.key);
      if (id === null || id === undefined) continue; // not set (the database refuses it) or a new parent
      const refuse = (reason) =>
        forbidden(reason, { kind: 'junction', collection, parent: check.parent, id: String(id) });
      if (!(await canUpdate(check, id, context))) {
        if (!(await createdInThisTransaction(check, id, context))) {
          throw refuse(JUNCTION_MESSAGES[`${collection}.${check.field}`] ?? 'You cannot change this record.');
        }
        continue; // a parent created by this very request is the creator's to build: no further check
      }
      const reason = await extraCheck(collection, check, id, item, context);
      if (reason) throw refuse(reason);
    }
  }

  const checked = (context) => context?.accountability?.user && context.accountability.admin !== true;
  const applies = (collection, context) => GUARDS[collection] !== undefined && checked(context);

  // The fields whose change needs the delete rule: the owner column and `restricted`.
  const guardFields = (guard) => guard.fields ?? [{ field: guard.field, valueKey: guard.valueKey }];

  // Has this guarded field of the stored row changed? A record the database does not know is a change
  // (the write will fail, but not on a guess). A nested object with no key (a new person) is a change.
  function fieldChanged(spec, row, value) {
    if (!row) return true;
    if (spec.field === 'restricted') {
      const next = pgBool(value);
      return next === null || pgBool(row.restricted) !== next;
    }
    const next = parentKey(value, spec.valueKey);
    const had = row[spec.field];
    return isBlank(had) ? next !== null : String(had) !== String(next);
  }

  // What a campaign's project change needs beyond "restricted is involved": the campaign's delete rule
  // and the delete rule of every restricted record it holds (see the header). Returns the refusal
  // message, or null.
  async function campaignMoveRefusal(id, context) {
    const db = context.database;
    if (!(await canPass(deleteCheck('campaigns'), [id], context))) return CAMPAIGN_MOVE;
    const links = await db('campaign_samples').where('campaign_id', id).select('sample_id');
    const sampleIds = [...new Set(links.map((r) => r.sample_id))];
    const samples = sampleIds.length
      ? await db('physical_samples').whereIn('sample_id', sampleIds).select('sample_id', 'restricted', 'project_id')
      : [];
    const projectIds = [...new Set(samples.map((s) => s.project_id).filter((p) => !isBlank(p)))];
    const projects = projectIds.length
      ? await db('projects').whereIn('project_id', projectIds).select('project_id', 'restricted')
      : [];
    const restrictedProjects = new Set(projects.filter((p) => toBool(p.restricted)).map((p) => String(p.project_id)));
    const operations = await db('manufacturing_operations')
      .where({ campaign_id: id, restricted: true })
      .select('operation_id');
    const tests = await db('test_sessions').where({ campaign_id: id, restricted: true }).select('session_id');
    const held = {
      physical_samples: samples
        .filter((s) => toBool(s.restricted) || restrictedProjects.has(String(s.project_id)))
        .map((s) => s.sample_id),
      manufacturing_operations: operations.map((r) => r.operation_id),
      test_sessions: tests.map((r) => r.session_id),
    };
    for (const [collection, ids] of Object.entries(held)) {
      if (ids.length && !(await canPass(deleteCheck(collection), ids, context))) return CAMPAIGN_CONTENT;
    }
    return null;
  }

  // The update checks of the four record types: the owner column and `restricted`, and moves.
  async function enforceRecord(collection, payload, keys, context) {
    const guard = OWNER_GUARDS[collection];
    const fields = guardFields(guard);
    const touched = fields.filter((f) => f.field in payload);
    const moves = (RESTRICTED_KEYS[collection] ?? []).filter((f) => f in payload);
    if (touched.length === 0 && moves.length === 0) return;
    const noun = OWNER_NOUNS[collection] ?? 'record';
    const db = context.database;

    const columns = new Set([guard.key, ...fields.map((f) => f.field), ...moves]);
    if (HAS_SAMPLE.has(collection)) columns.add('sample_id');
    const stored = await db(collection).whereIn(guard.key, keys).select(...columns);
    const rows = new Map(stored.map((row) => [String(row[guard.key]), row]));

    // Which records need the delete rule, and why (the first reason wins).
    const need = new Map();
    const movedKeys = new Map(); // record key -> the move fields whose value changes
    for (const key of keys) {
      const row = rows.get(String(key));
      if (restrictAdminOnly() && touched.some((f) => f.field === 'restricted' && fieldChanged(f, row, payload.restricted))) {
        throw forbidden(RESTRICT_REFUSED, { kind: 'restricted', collection, id: String(key) });
      }
      const changedField = touched.find((f) => fieldChanged(f, row, payload[f.field]));
      if (changedField) need.set(key, changedField.field === 'restricted' ? 'restricted' : 'owner');
      const moved = moves.filter((f) => {
        const next = parentKey(payload[f], f);
        if (!row) return true;
        // Clearing a key is a move too: it takes the record out of its parent's gate (an operation out of a restricted sample,
        // a sample out of a restricted project), so it needs the owner whenever the OLD parent is restricted.
        if (next === null) return !isBlank(row[f]);
        return next === undefined || String(row[f]) !== String(next);
      });
      if (moved.length) movedKeys.set(key, moved);
    }

    // A move needs the delete rule when the record, its current sample, or an old or new parent is
    // Restricted. One read per parent table, for the records that move.
    if (movedKeys.size) {
      const wanted = { project_id: new Set(), campaign_id: new Set(), sample_id: new Set() };
      for (const [key, moved] of movedKeys) {
        const row = rows.get(String(key)) ?? {};
        for (const f of moved) {
          for (const id of [row[f], parentKey(payload[f], f)]) if (!isBlank(id)) wanted[f].add(String(id));
        }
        if (HAS_SAMPLE.has(collection) && !isBlank(row.sample_id)) wanted.sample_id.add(String(row.sample_id));
      }
      // "restricted" here is HIDDEN: the flag or d1_private.hidden_records (an unrestricted sample in a restricted project is hidden)
      const restrictedIn = {};
      for (const [f, ids] of Object.entries(wanted)) {
        const [table, pk] = MOVE_PARENTS[f];
        restrictedIn[f] = await hiddenIn(db, table, pk, [...ids]);
      }
      const ownHidden = await hiddenIn(db, collection, guard.key, [...movedKeys.keys()], { flag: false });
      for (const [key, moved] of movedKeys) {
        const row = rows.get(String(key)) ?? {};
        const involved =
          toBool(row.restricted) ||
          ownHidden.has(String(key)) ||
          (HAS_SAMPLE.has(collection) && restrictedIn.sample_id.has(String(row.sample_id))) ||
          moved.some((f) => {
            const next = parentKey(payload[f], f);
            return restrictedIn[f].has(String(row[f])) || (!isBlank(next) && restrictedIn[f].has(String(next)));
          });
        if (involved) need.set(key, 'move');
      }
    }

    // A campaign's project change always needs the campaign's owner, and the owner of what is restricted in it.
    const campaignMoves = new Set();
    if (collection === 'campaigns') {
      for (const [key, moved] of movedKeys) if (moved.includes('project_id')) campaignMoves.add(key);
    }

    const reasons = {
      owner: [`Only the ${noun}'s owner can hand it to someone else.`, 'owner'],
      restricted: [`Only the ${noun}'s owner can restrict it or lift the restriction.`, 'restricted'],
      move: [`Only the ${noun}'s owner can move it into or out of something restricted.`, 'restricted'],
    };
    const refuse = (key, text, kind) => forbidden(text, { kind, collection, id: String(key) });
    for (const key of keys) {
      if (campaignMoves.has(key)) {
        const text = await campaignMoveRefusal(key, context);
        if (text) throw refuse(key, text, 'restricted');
      }
      const why = need.get(key);
      if (!why || campaignMoves.has(key)) continue; // (a campaign move already passed the delete rule)
      // Whoever owns a record may delete it, which is why only the owner may hand it over or restrict it.
      if (!(await canPass(deleteCheck(collection), [key], context))) throw refuse(key, ...reasons[why]);
    }
  }

  // Removing a sample from a Restricted campaign can unhide what the campaign shielded (its operations and tests), so it needs
  // the campaign's owner (its delete rule); an admin is not checked. A campaign that is not Restricted keeps the junction rule.
  filter('items.delete', async (payload, meta, context) => {
    const collection = meta?.collection;
    if ((collection !== 'campaign_samples' && collection !== 'test_sessions_subject') || !checked(context)) return payload;
    const keys = (Array.isArray(payload) ? payload : meta.keys ?? []).filter((k) => !isBlank(k) && typeof k !== 'object');
    if (!keys.length) return payload;
    const pk = context.schema?.collections?.[collection]?.primary ?? 'id';
    const db = context.database;
    if (collection === 'test_sessions_subject') {
      // Removing a subject row can leave a test with no sample (it then leaves the sample's gate, the migration-139 trigger) or on another one
      const rows = await db('test_sessions_subject').whereIn(pk, keys).select(pk, 'test_sessions_id', 'item', 'collection');
      if (rows.length && (await subjectChangeRefused(rows.map((r) => r.test_sessions_id), rows.map(subjectSample).filter(Boolean), context))) {
        throw forbidden(SUBJECT_MOVE, { kind: 'junction', collection, parent: 'test_sessions', id: String(rows[0].test_sessions_id) });
      }
      return payload;
    }
    const rows = await db('campaign_samples').whereIn(pk, keys).select(pk, 'campaign_id');
    const campaignIds = [...new Set(rows.map((r) => r.campaign_id).filter((c) => !isBlank(c)))];
    if (!campaignIds.length) return payload;
    // hidden, not just flagged: a campaign of a restricted project shields its samples' operations too
    const locked = [...(await hiddenIn(db, 'campaigns', 'campaign_id', campaignIds))];
    if (locked.length && !(await canPass(deleteCheck('campaigns'), locked, context))) {
      throw forbidden(REMOVE_FROM_RESTRICTED_CAMPAIGN, { kind: 'junction', collection: 'campaign_samples', parent: 'campaigns', id: String(locked[0]) });
    }
    return payload;
  });

  // Repointing `item`, `collection` or `test_sessions_id` of a subject row: the same rule as removing it (see subjectChangeRefused). A value sent
  // unchanged (an editor saving the whole form) is not a change.
  async function enforceSubjectUpdate(payload, meta, context) {
    const touched = ['item', 'collection', 'test_sessions_id'].filter((field) => field in payload);
    const keys = Array.isArray(meta.keys) ? meta.keys.filter((k) => !isBlank(k)) : [];
    if (!touched.length || !keys.length) return;
    const db = context.database;
    const pk = context.schema?.collections?.test_sessions_subject?.primary ?? 'id';
    const rows = await db('test_sessions_subject').whereIn(pk, keys).select(pk, 'test_sessions_id', 'item', 'collection');
    const next = { ...payload };
    if ('test_sessions_id' in payload) next.test_sessions_id = parentKey(payload.test_sessions_id, 'session_id');
    const tests = new Set();
    const samples = new Set();
    let changed = rows.length === 0; // a row the database does not know: not a guess
    for (const row of rows) {
      const after = { ...row, ...Object.fromEntries(touched.map((f) => [f, next[f]])) };
      if (touched.some((f) => String(next[f] ?? '') !== String(row[f] ?? ''))) changed = true;
      tests.add(row.test_sessions_id);
      if (!isBlank(after.test_sessions_id)) tests.add(after.test_sessions_id);
      for (const s of [subjectSample(row), subjectSample(after)]) if (s) samples.add(s);
    }
    if (!changed) return;
    if (await subjectChangeRefused([...tests], [...samples], context)) {
      throw forbidden(SUBJECT_MOVE, { kind: 'junction', collection: 'test_sessions_subject', parent: 'test_sessions', id: String([...tests][0] ?? '') });
    }
  }

  filter('items.create', async (payload, meta, context) => {
    // Until A1b, a non-admin cannot create a record already restricted (an explicit false, or no value, is fine)
    if (restrictable(meta?.collection) && checked(context) && payload && restrictAdminOnly()) {
      for (const item of Array.isArray(payload) ? payload : [payload]) {
        if (item && typeof item === 'object' && !isBlank(item.restricted) && pgBool(item.restricted) !== false) {
          throw forbidden(RESTRICT_REFUSED, { kind: 'restricted', collection: meta.collection, id: '' });
        }
      }
    }
    if (!applies(meta?.collection, context) || !payload) return payload;
    for (const item of Array.isArray(payload) ? payload : [payload]) {
      if (item && typeof item === 'object') await enforce(meta.collection, item, null, context);
    }
    return payload;
  });

  filter('items.update', async (payload, meta, context) => {
    if (!checked(context) || !payload || typeof payload !== 'object') return payload;
    const collection = meta?.collection;
    if (collection === 'projects' && restrictAdminOnly() && 'restricted' in payload) {
      // projects have no owner guard (only the PI can update one), but the PI can restrict it: refused until A1b like the other four
      const keys = Array.isArray(meta.keys) ? meta.keys.filter((key) => !isBlank(key)) : [];
      const stored = keys.length ? await context.database('projects').whereIn('project_id', keys).select('project_id', 'restricted') : [];
      const byKey = new Map(stored.map((r) => [String(r.project_id), r]));
      for (const key of keys) {
        if (fieldChanged({ field: 'restricted' }, byKey.get(String(key)), payload.restricted)) {
          throw forbidden(RESTRICT_REFUSED, { kind: 'restricted', collection, id: String(key) });
        }
      }
    }
    if (OWNER_GUARDS[collection]) {
      const keys = Array.isArray(meta.keys) ? meta.keys.filter((key) => !isBlank(key)) : [];
      if (keys.length) await enforceRecord(collection, payload, keys, context);
      return payload;
    }
    if (!applies(collection, context)) return payload;
    if (collection === 'test_sessions_subject') await enforceSubjectUpdate(payload, meta, context);
    // Only an update that repoints a parent key can grant anything; checking the new target is
    // enough, because the row's old parent was already allowed when it was written. A key sent
    // with its current value (an editor saving the whole form) is not a change.
    const guards = GUARDS[collection];
    const all = guards.map((c) => c.field);
    const touched = all.filter((f) => f in payload);
    if (touched.length === 0) return payload;
    const keys = Array.isArray(meta.keys) ? meta.keys : [];
    const pk = context.schema?.collections?.[collection]?.primary ?? 'id';
    const existing = keys.length ? await context.database(collection).whereIn(pk, keys).select(pk, ...all) : [];
    const rows = existing.length ? existing : [{}];
    const changed = new Set();
    for (const field of touched) {
      const next = parentKey(payload[field], guards.find((c) => c.field === field).key);
      if (next === null) continue; // clearing a parent key grants nothing (and the database refuses it)
      if (next === undefined || rows.some((row) => String(row[field]) !== String(next))) changed.add(field);
    }
    if (changed.size === 0) return payload;
    if (guards.length === 1) {
      await enforce(collection, payload, changed, context);
      return payload;
    }
    // A junction with several guards (campaign_samples) grants through the PAIR of keys, so moving
    // one key must still satisfy every guard: check the row as it will be after the update.
    for (const row of rows) await enforce(collection, { ...row, ...payload }, null, context);
    return payload;
  });
};
