// Directus hook: d1-access-guard (ADR-0011)
//
// Row-level visibility (ADR-0011) is a set of Directus permission filters on the Lab Member policy.
// Four junction collections are part of those filters, so writing a row in one of them changes who
// can read a record:
//
//   sample_co_owners      a co-owner can read and edit the sample
//   project_investigators an investigator can read everything in the project
//   campaign_samples      a campaign's owner can read every sample in it
//   test_sessions_subject a trigger (migration 139) copies the test's first sample into
//                         test_sessions.sample_id, and the sample's owner and co-owners read and
//                         edit the test through it
//
// Directus does not apply item filters to *create* (and `validation` cannot reach across relations),
// so with the plain permissions any member could add themselves to a sample they cannot edit, to a
// project they do not lead, or add someone else's sample to their own campaign, and so read it. This
// hook closes that. It refuses a create (or an update that repoints a parent key) unless the caller
// may change the parent row: for sample_co_owners the sample's owner, for project_investigators the
// project's PI (the parent's DELETE rule, A1a), for test_sessions_subject the test (update rule) and for
// campaign_samples BOTH the campaign and the sample (update rules).
//
// On update, only a parent key that changes is checked. A junction with several guards
// (campaign_samples) grants through the pair of keys, so when either key changes every guard is
// checked on the merged row ({...currentRow, ...payload}).
//
// The check is the parent's own rule (update, or delete where scripts/access_rules.json says 'rule') shipped as
// rules.json (generated by scripts/gen_access_rules.py; a drift check runs in CI and pre-commit), run
// through ItemsService with the caller's accountability, so nothing here restates the rules by hand.
//
// A second check closes a gap in the owner column. Several records may be updated by more people than
// may delete them (a sample: owner and co-owners update, only the owner deletes). Changing the owner
// column would hand delete to whoever changes it, so an update that changes it is refused unless the
// caller passes the record's DELETE rule, i.e. is its current owner. The owner may hand a record over;
// an editor may not take it. rules.json carries that rule as `ownerGuards`, with the list of fields it
// covers: the owner column and `restricted` (A1a). Only the owner switches a record to or from
// Restricted; a Can edit person may not, even though they may edit every other field.
//
// Ruling O4 (People 3) holds on this direct path too: an update that sets `owner_team_id` to a team with no manager (no is_manager row in
// team_members) is refused 409 TEAM_HAS_NO_MANAGER, after the owner check above; administrators and internal calls are exempt.
//
// A third check (A1a, `restrictedKeys`) covers moving a record. Moving a sample, operation, test or
// campaign to another project, campaign or sample changes who can see it, which is managing its access
// by another name. When the record, its current sample, or the old or new project, campaign or sample
// is Restricted, the update must pass the record's DELETE rule (its owner), else 403. The flags are read
// straight from the database in the request's transaction (`restricted` is hidden in Directus and the
// parent may not be readable to the caller).
//
// A fourth check (ADR-0019, planned work) covers the work state of operations and tests: an update that sets `work_state` to
// 'planned' on a record that is 'done' must pass the record's DELETE rule (its owner), else 403 ("Only the owner can set a done
// record back to planned."). When the move is allowed, the same payload also clears operation_date / session_date,
// done_by_person_id and done_at (a planned record has none). Admins and internal calls are not checked. Marking a record done is not guarded: whoever may edit it
// may do that (the d1-build endpoint).
//
// Two more writes could be used to read what a restriction hides, so they are guarded here (the readers
// tables recompute correctly from them; the question is who may write them):
//   * a campaign_samples row (create or repoint) needs the caller to be a READER of the sample
//     (sample_readers, one lookup) on top of the sample's update rule, and when the sample is
//     Restricted its owner (the sample's delete rule);
//   * a change of campaigns.project_id needs the campaign's delete rule (its owner; a Can edit person is
//     refused) and, when the campaign holds a Restricted sample, a Restricted operation or test with that
//     campaign_id, or a sample of a Restricted project, also each of those records' delete rule. Without
//     the last part a campaign owner could move their campaign into a project they created themselves
//     (they are its PI) and so read every record in it. Otherwise only an admin may make the move.
// A test_sessions_subject row on a Restricted test, or a test whose sample is Restricted, needs the
// test's delete rule (the migration-139 trigger derives test_sessions.sample_id from the subject rows).
//
// sample_co_owners and project_investigators use the parent's DELETE rule (A1a: only the owner adds a
// co-owner, only the PI adds an investigator). The Who-has-access endpoint (d1-record-access) writes the
// access tables with system accountability after its own manage check, so it is not guarded here.
//
// "Involved" in the checks above means HIDDEN, not merely flagged: a record is involved when it is Restricted or when d1_private.hidden_records
// lists it (restricted, or under a restricted project, campaign or sample; kept by the readers triggers of migration 166). The bare flag of a parent
// is not enough: an operation on an unrestricted sample in a restricted project is gated by the project, and moving it away lifts that gate. The two
// reads are united (flag OR hidden_records), so an empty hidden_records after a restore can only make the guard stricter, never looser.
// test_sessions_subject is guarded on create, on repointing `item`/`collection`/`test_sessions_id` and on delete: the migration-139 trigger derives
// test_sessions.sample_id from the rows, so changing or removing one moves the test between sample gates.
//
// Until A1b ships, NO non-admin may change `restricted` on any of the four record types, on update or at create (RESTRICT_ADMIN_ONLY below): the files
// and octrees of a restricted record are not yet protected, so letting owners switch it would promise privacy the system cannot keep. Admins can. The
// owner-only logic underneath stays for A1b.
//
// A fifth junction is not a visibility grant but follows the same pattern (ADR-0023): surface_scans.directus_files_id. A scan of an OWNED file may be
// created, or repointed to another file, only by a caller who can read that file (the read rule of directus_files, run as the caller, so the owner,
// the owning team's members and an administrator pass and an unowned file is open); a file id that does not exist is refused with the same
// words. directus_files has no OCC `version` column, so the created-in-this-transaction shortcut above never applies to it.
// A sixth is not a visibility grant either (Conform runs, plan 2026-10-21-conform-runs, review round 1): conform_run_data.operation_id (the caller must
// pass the operation's update rule: Directus does not filter create, and the Lab Member create row is `{}`) and conform_run_data.log_id (the log must exist;
// logs are readable by every member, so its rule is an empty filter).
// A seventh follows ADR-0022 (a file belongs to whoever it came from): conform_logs.directus_files_id. A log may be created only over a file the
// caller uploaded (directus_files.uploaded_by) that sits in the Conform Logs folder; the guard carries that literal filter (access_rules.json) and
// runs it as the caller, and a file id that does not exist gets the same words. Without it a member could point a log at someone else's file, and
// d1-conform-guard's file lock (with the non-cascading foreign key) would then stop the file's owner renaming, replacing or deleting it.
// Migration 211 holds the same rule as a BEFORE INSERT trigger (the backstop for every writer that sets created_by).
// For the same reason a non-admin may not change who uploaded a file (`uploaded_by`): the Lab Member field list of directus_files includes it
// (a field list cannot say "not this value", and narrowing it waits for SEM3), so a member could otherwise restamp an unowned file as theirs and
// then pass the rule above. Directus stamps the column itself on upload (special user-created), so only an update can change it.
//
// Admins, and calls with no accountability (flows, scripts, other extensions), are not checked.
// Everyone else is, whatever their policy, because the rules are the Lab Member rules.
//
// Lab Viewer (migration 185, ADR-0014 amendment): the role reads everything and changes nothing. Its policy has no create, update or delete
// permission row, so Directus refuses every item write. But Directus gives EVERY app_access policy a built-in right to create comments (and to
// update and delete its own), and that right is not a row in directus_permissions, so no policy can take it away. The three hooks at the end of
// this file (comments.create, comments.update, comments.delete) refuse a caller whose ROLE is the Lab Viewer role with 403 READ_ONLY_ROLE, whatever
// the login's status (fail closed) and whatever else the login holds. Only the role decides, so an administrator (another role) is unaffected.
// What a viewer can still write on purpose is listed in docs/adr/0014-record-access.md (the Lab Viewer amendment).
//
// Creating a parent and its junction rows in one request (a project with investigators, a sample with
// co-owners, a campaign with samples) is allowed. The parent has just been inserted, in the request's
// transaction, so its update rule may not hold for the creator (they named someone else as owner or
// PI), yet the creator is the one making that record. A parent key therefore also passes when the
// parent row was inserted by the current transaction (Postgres: its xmin is this transaction's id),
// without checking its update rule. Only a row INSERTED here and never updated since can match
// (xmin is this transaction AND the OCC version is still 1), so neither a row that merely exists nor
// a pre-existing row that was updated in this transaction (by this request, an FK action or a
// trigger) qualifies, and this never lets a member attach themselves to a record someone else made. The sample of
// a campaign_samples row is still checked (it is a different row) unless it is new too. A row
// created inside a savepoint carries the sub-transaction id and is not recognised: that fails closed
// (refused); Directus does not use savepoints.
// A payload that nests a brand-new parent (no key) is allowed: the caller is creating that record.

