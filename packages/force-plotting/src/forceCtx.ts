export const FORCE_CTX: InjectionKey<ForceCtx> = Symbol('force-dashboard');

export function useForceCtx(): ForceCtx {
	const ctx = inject(FORCE_CTX);
	if (!ctx) throw new Error('useForceCtx() needs a ForceDashboard above it');
	return ctx;
}
